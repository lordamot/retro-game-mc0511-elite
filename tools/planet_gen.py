#!/usr/bin/env python3
"""planet_gen.py - src/res/text/planet.txt -> the tables the game reads.

Four lists for the species - size, colour, characteristic and kind - and
three for the description - hazards, sights and qualities.  Each comes
out as a table of pointers plus a count, so `src/planet.mac` can index
them the way Elite indexes its own.

    python3 tools/planet_gen.py src/res/text/planet.txt --out build/planet.mac
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import text_gen                                    # noqa: E402

GROUPS = ["size", "colour", "trait", "kind", "hazard", "sight", "quality"]


def read(path):
    rows = {g: [] for g in GROUPS}
    with open(path, encoding="utf-8") as fh:
        for lineno, raw in enumerate(fh, 1):
            line = raw.split("#", 1)[0].rstrip("\n")
            if not line.strip():
                continue
            parts = line.split("\t")
            if len(parts) < 4:
                sys.exit(f"{path}:{lineno}: want group, address, stem, text")
            group, _addr, _stem, shown = parts[0], parts[1], parts[2], parts[3]
            if group not in rows:
                sys.exit(f"{path}:{lineno}: unknown group {group!r}")
            rows[group].append(shown)
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("score", nargs="?", default="src/res/text/planet.txt")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    rows = read(args.score)

    out = ["; Generated by tools/planet_gen.py - do not edit.",
           f"; Source: {os.path.relpath(args.score)}", ""]
    for group in GROUPS:
        words = rows[group]
        name = group.upper()
        out.append(f"N{name}\t= {len(words)}.")
        out.append(f"{name}TAB:")
        for i, _w in enumerate(words):
            out.append(f"\t\t.WORD\tPW_{name}{i}")
        out.append("")
    for group in GROUPS:
        for i, word in enumerate(rows[group]):
            koi = text_gen.to_koi7(word, f"{group}[{i}]")
            body = ", ".join(f"{b}." for b in koi) if koi else ""
            body = (body + ", 0") if body else "0"
            out.append(f"PW_{group.upper()}{i}:\t.BYTE\t{body}")
    out.append("\t\t.EVEN")
    out.append("")
    text = "\n".join(out)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"-> {args.out}: {sum(len(v) for v in rows.values())} words")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
