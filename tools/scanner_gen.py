#!/usr/bin/env python3
"""scanner_gen.py - Elite Legend's scanner dishes: extract them, and
compile them for the dashboard overlay.

Legend draws each cockpit's scanner from one of five packed pictures
(Cocpits/Scaner/*.zxp, chosen by the cockpit block's cocpScanerNum
through AdrDataScaner in Engine/cocpPrnInit.a80): Base (1), THD (2, 3),
Kladov (4), Targon (5, 6) and the Locator (0, which no cockpit uses).
The four the cockpits use are kept here as text, one character a pixel,
rows 6..51 of Legend's 120x56 (the rows any of them uses):

    == base            a section per dish, in Legend's order
    ....###...         . empty, # lit

    python3 tools/scanner_gen.py --extract DIR --out src/res/legend/scanners.txt
    python3 tools/scanner_gen.py src/res/legend/scanners.txt --out build/scanners.mac

The compiled form is for src/ovl_dash.mac:
- SC_ROWS rows of SC_W bytes (bit 0 the leftmost pixel) a dish, each
  dish one run-length stream (a control byte c: 0..127 is c+1 literal
  bytes following, 128..255 is c-127 empty bytes), at SC_ART's words;
- SC_OF, a byte for each cocpScanerNum 0..6: which dish to draw.
"""

import argparse
import sys
from pathlib import Path

DISHES = [("base", "scBase"), ("thd", "scTHD_2"), ("kladov", "scKladov2"), ("targon", "scTargon")]
OF = [0, 0, 1, 1, 2, 3, 3]          # cocpScanerNum 0..6; the Locator (0) draws as Base
ROW0, NROWS, WIDTH = 6, 46, 120


def read_zxp(path: Path):
    rows = [ln.strip() for ln in path.read_text(encoding="latin1").splitlines()[2:]
            if ln.strip() and set(ln.strip()) <= set("01")]
    if len(rows) != 56 or any(len(r) != WIDTH for r in rows):
        sys.exit(f"error: {path} is not a 120x56 ZX-Paintbrush picture")
    return rows


def extract(src: Path) -> str:
    out = ["# Elite Legend's scanner dishes (Cocpits/Scaner/*.zxp), rows 6..51 of",
           "# 120x56, one section a dish in the order of AdrDataScaner's pictures:",
           "# base (cocpScanerNum 1), thd (2, 3), kladov (4), targon (5, 6).",
           "# . empty, # lit.  tools/scanner_gen.py compiles it."]
    for name, fn in DISHES:
        rows = read_zxp(src / f"{fn}.zxp")
        out.append(f"== {name}")
        out += [r.replace("0", ".").replace("1", "#") for r in rows[ROW0:ROW0 + NROWS]]
    return "\n".join(out) + "\n"


def rle(flat):
    out, i = [], 0
    while i < len(flat):
        j = i
        if flat[i] == 0:
            while j < len(flat) and flat[j] == 0 and j - i < 128:
                j += 1
            out.append(127 + (j - i))
        else:
            while j < len(flat) and flat[j] != 0 and j - i < 128:
                j += 1
            out.append(j - i - 1)
            out += flat[i:j]
        i = j
    return out


def compile_dishes(txt: Path):
    dishes, cur = {}, None
    for ln in txt.read_text(encoding="utf-8").splitlines():
        if not ln or ln.startswith("#"):
            continue
        if ln.startswith("== "):
            cur = ln[3:].strip()
            dishes[cur] = []
        elif cur:
            dishes[cur].append(ln)
    names = [n for n, _ in DISHES]
    if list(dishes) != names:
        sys.exit(f"error: the dishes must be {names}, in that order")
    for n, rows in dishes.items():
        if len(rows) != NROWS or any(len(r) != WIDTH for r in rows) or set("".join(rows)) - set(".#"):
            sys.exit(f"error: dish {n} must be {NROWS} rows of {WIDTH} '.' or '#'")
    wb = WIDTH // 8
    out = ["; Generated by tools/scanner_gen.py - do not edit.",
           f"; Source: {txt.as_posix()}", "",
           f"SC_ROWS	= {NROWS}.", f"SC_W	= {wb}.",
           "SC_OF:		.BYTE\t" + ", ".join(f"{v}." for v in OF), "\t\t.EVEN",
           "SC_ART:		.WORD\t" + ", ".join(f"SC_{n.upper()}" for n in names)]
    total = 0
    for n in names:
        flat = []
        for r in dishes[n]:
            for cx in range(wb):
                b = 0
                for k in range(8):
                    if r[cx * 8 + k] == "#":
                        b |= 1 << k
                flat.append(b)
        data = rle(flat)
        total += len(data)
        out.append(f"SC_{n.upper()}:")
        for k in range(0, len(data), 16):
            out.append("\t\t.BYTE\t" + ", ".join(f"{v}." for v in data[k:k + 16]))
    out.append("\t\t.EVEN")
    return "\n".join(out) + "\n", total


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("src", nargs="?", help="the dishes as text, to compile")
    ap.add_argument("--extract", metavar="DIR", help="Legend's Cocpits/Scaner directory")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true", help="accepted for the build; always writes")
    args = ap.parse_args(argv)
    if args.extract:
        Path(args.out).write_text(extract(Path(args.extract)), encoding="utf-8")
        print(f"-> {args.out}: extracted")
        return
    if not args.src:
        sys.exit("error: give the dishes' text file, or --extract")
    text, n = compile_dishes(Path(args.src))
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"-> {args.out}: {len(DISHES)} dishes, {n} bytes")


if __name__ == "__main__":
    main()
