#!/usr/bin/env python3
"""text_gen.py - src/res/text/strings.txt -> MACRO-11 byte arrays.

Each "LABEL|text" line becomes S_<LABEL>, a 0-terminated array in KOI-7,
the encoding the original's own text uses and the one src/text.mac's
font is laid out in.  Cyrillic is folded to uppercase first, because the
font has no lowercase.  A line `@overlay NAME` starts a section whose
strings go to strings_NAME.mac beside --out, for that overlay (two
names on the line, and both overlays get the section)
(src/ovl.list) to assemble; everything before the first tag is the
resident's.

    python3 tools/text_gen.py src/res/text/strings.txt --out build/strings.mac
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import elite_re                                   # noqa: E402

UNI2KOI = {v: k for k, v in elite_re.KOI7.items()}


def to_koi7(text, label):
    out = []
    for ch in text.upper():
        if ch in UNI2KOI:
            out.append(ord(UNI2KOI[ch]))
        elif 0x20 <= ord(ch) < 0x60:
            out.append(ord(ch))
        elif ch == "Ё":
            out.append(ord(UNI2KOI["Е"]))
        else:
            raise SystemExit(f"{label}: character {ch!r} has no KOI-7 place")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("source")
    ap.add_argument("--out", required=True)
    ap.add_argument("--pairs",
                    help="src/res/text/pairs.txt; emits NAMEPAIRS, the 32 "
                         "syllables the galaxy generator names systems from")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    if os.path.exists(args.out) and not args.force:
        sys.exit(f"error: {args.out} exists (use --force)")

    # the resident's strings, then one list per `@overlay NAME` section:
    # those go to <out dir>/strings_NAME.mac for that overlay to assemble
    sections = {"": []}
    current = ("",)
    seen = set()
    with open(args.source, encoding="utf-8") as fh:
        for lineno, raw in enumerate(fh, 1):
            line = raw.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            if line.startswith("@overlay"):
                # `@overlay a b`: the section's strings go to both a and b
                current = tuple(line[len("@overlay"):].split())
                for name in current:
                    sections.setdefault(name, [])
                continue
            if "|" not in line:
                sys.exit(f"{args.source}:{lineno}: no '|' in {line!r}")
            label, text = line.split("|", 1)
            label = label.strip()
            if label in seen:
                sys.exit(f"{args.source}:{lineno}: duplicate label {label}")
            seen.add(label)
            for name in current:
                sections[name].append((label, to_koi7(text, label), text))
    entries = sections[""]

    def write_strings(path, items, note):
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("; Generated by tools/text_gen.py - do not edit.\n")
            fh.write(f"; Source: {args.source}{note}\n\n")
            for label, data, text in items:
                body = ", ".join(str(b) + "." for b in data) or "0"
                fh.write(f"S_{label}:\t.BYTE\t{body}, 0\t; {text}\n")
                fh.write("\t\t.EVEN\n")

    outdir = os.path.dirname(os.path.abspath(args.out))
    for name, items in sections.items():
        if name:
            write_strings(os.path.join(outdir, f"strings_{name}.mac"), items,
                          f", the `@overlay {name}` section")
            print(f"-> {os.path.join(outdir, f'strings_{name}.mac')}: "
                  f"{len(items)} strings")
    with open(args.out, "a" if False else "w", encoding="utf-8") as fh:
        fh.write("; Generated by tools/text_gen.py - do not edit.\n")
        fh.write(f"; Source: {args.source}, the resident's strings\n\n")
        for label, data, text in entries:
            body = ", ".join(str(b) + "." for b in data) or "0"
            fh.write(f"S_{label}:\t.BYTE\t{body}, 0\t; {text}\n")
            fh.write("\t\t.EVEN\n")
        if args.pairs:
            pairs = []
            with open(args.pairs, encoding="utf-8") as pf:
                for line in pf:
                    if line.lstrip().startswith("#"):
                        continue
                    tok = line.split(";", 1)[0].split("#", 1)[0].strip()
                    if tok:
                        if len(tok) != 2:
                            sys.exit(f"{args.pairs}: {tok!r} is not a pair")
                        pairs.append(tok)
            fh.write("\n; The syllables system names are built from, two\n"
                     "; bytes each - the same table the original uses as\n"
                     "; its two-letter text tokens.\n")
            fh.write(f"NPAIRS\t= {len(pairs)}.\n")
            fh.write("NAMEPAIRS:\n")
            for i, pr in enumerate(pairs):
                b = ", ".join(str(ord(c)) + "." for c in pr)
                fh.write(f"\t\t.BYTE\t{b}\t; {i:2d}\n")
    print(f"-> {args.out}: {len(entries)} strings")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
