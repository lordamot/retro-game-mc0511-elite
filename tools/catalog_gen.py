#!/usr/bin/env python3
"""Elite Legend's ship catalogue as a MACRO-11 module.

Reads src/res/legend/catalog.txt (tools/legend_tables.py's extract of
INCLUDE/Menu/InfoShips.a80: the twenty ships the yard can sell, in the
order PilotNumShip counts them from 1) and writes build/legend_catalog.mac,
one table a column, every one indexed by PilotNumShip - 1:

    NSHIPS_L        ships (20)
    SHIP_FIT        .BYTE, six a ship: which equipment fits - bit 7 of
                    the first byte is equipment row 1, bit 6 row 2 ...
                    (TestShipEquip in EquipShip.a80; row 0, fuel, always
                    fits)
    SHIP_PRICE      .WORD low, high a ship: tenths of a credit
    SHIP_TONS       .WORD a ship: the hold
    SHIP_DATE       .WORD a ship: the in-service year, 0 unknown
    SHIP_SPEED      .BYTE a ship
    SHIP_HULL       .BYTE a ship: AdrDataShips number of its hull
    SHIP_COCKPIT    .BYTE a ship: which of the twenty cockpits
    SHIP_ECOTECH    .BYTE a ship: bits 7-5 the economy, 4-0 the tech
                    level a system needs to sell it
    SHIP_CHANCE     .BYTE a ship: of being for sale
    SHIP_MISSION    .BYTE a ship: the PilotMissionComplete gate

The outfitter (src/ovl_equip.mac) reads SHIP_FIT and SHIP_PRICE; the
yard (src/ovl_yard.mac) the rest.
"""

import argparse
import os
import sys

FIELDS = ["date", "speed", "tonnage", "price", "obj", "cockpit", "base_tonnage",
          "fit0", "fit1", "fit2", "fit3", "fit4", "fit5", "ecotech", "chance",
          "mission"]


def read_catalog(path):
    rows = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            head, _, vals = line.partition("|")
            n, name = head.split(None, 1)
            v = vals.split()
            if len(v) != len(FIELDS):
                sys.exit(f"{path}: cannot read: {line!r}")
            r = dict(zip(FIELDS, (int(x) for x in v)))
            r["n"] = int(n)
            r["name"] = name.strip()
            rows.append(r)
    for i, r in enumerate(rows):
        if r["n"] != i + 1:
            sys.exit(f"{path}: row {i + 1} is numbered {r['n']}")
    return rows


def emit(rows, source, part="all"):
    """PART "fit" is the fit masks and the prices, all the outfitter
    reads; "all" the yard's whole catalogue."""
    out = ["; Generated by tools/catalog_gen.py - do not edit.",
           f"; Source: {source} (part: {part})", "",
           f"NSHIPS_L\t= {len(rows)}.", ""]
    out.append("SHIP_FIT:")
    for r in rows:
        fit = ", ".join(f"{r[f'fit{i}']}." for i in range(6))
        out.append(f"\t\t.BYTE\t{fit}\t; {r['n']} {r['name']}")
    out.append("\t\t.EVEN")
    out.append("SHIP_PRICE:")
    for r in rows:
        out.append(f"\t\t.WORD\t{r['price'] & 0xFFFF}., {r['price'] >> 16}.\t; {r['n']}")
    if part == "fit":
        return "\n".join(out) + "\n"
    out.append("SHIP_TONS:\t.WORD\t" + ", ".join(f"{r['tonnage']}." for r in rows))
    out.append("SHIP_DATE:\t.WORD\t" + ", ".join(f"{r['date']}." for r in rows))
    for label, field in (("SHIP_SPEED", "speed"), ("SHIP_HULL", "obj"),
                         ("SHIP_COCKPIT", "cockpit"), ("SHIP_ECOTECH", "ecotech"),
                         ("SHIP_CHANCE", "chance"), ("SHIP_MISSION", "mission")):
        out.append(f"{label}:\t.BYTE\t" + ", ".join(f"{r[field]}." for r in rows))
    out.append("\t\t.EVEN")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("source", help="src/res/legend/catalog.txt")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--part", choices=["all", "fit"], default="all",
                    help="which columns: all (the yard), fit (the outfitter)")
    args = ap.parse_args(argv)
    if os.path.exists(args.out) and not args.force:
        sys.exit(f"error: {args.out} exists (use --force)")
    rows = read_catalog(args.source)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(emit(rows, args.source, args.part))
    print(f"-> {args.out}: {len(rows)} ships ({args.part})")


if __name__ == "__main__":
    main()
