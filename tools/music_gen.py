#!/usr/bin/env python3
"""music_gen.py - a text score -> the MACRO-11 table the PPU's tune plays.

MUS_TICK (src/ppu.mac) walks a list of steps on the SECOND AY chip, each

    .WORD  tone period
    .BYTE  volume, frames

ended by a period of -1: a note list, which this writes from note names.
(The effects are Legend's own, on the first chip: tools/sfx_gen.py.)

The period is for the module's own 1.77 MHz clock:

    period = clock / (16 * frequency)

Note that UKNCBTL clocks its AY slower than a real module, so the tune
comes out lower in the emulator than on hardware - the same caveat the
effects carry.

    python3 tools/music_gen.py src/res/music/title.txt --out build/music.mac
"""

import argparse
import os
import re
import sys

AY_CLOCK = 1773400.0
SEMITONE = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6,
            "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}
NOTE = re.compile(r"^([A-G]#?)(\d)$")
VOLUME = 12                     # steady: a title tune, not an effect


def frequency(name):
    m = NOTE.match(name)
    if not m:
        raise ValueError(f"not a note: {name!r}")
    step = SEMITONE[m.group(1)] + 12 * (int(m.group(2)) - 4)
    return 440.0 * 2.0 ** ((step - 9) / 12.0)      # A4 = 440


def period(name):
    return int(round(AY_CLOCK / (16.0 * frequency(name))))


def read_score(path):
    out = []
    with open(path, encoding="utf-8") as fh:
        for lineno, raw in enumerate(fh, 1):
            # A comment starts the line or follows whitespace: a bare
            # "#" is part of a note name, and F#4 is not a comment.
            line = re.split(r"(?:^|\s)#", raw, maxsplit=1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) != 2:
                sys.exit(f"{path}:{lineno}: want 'NOTE FRAMES'")
            name, frames = parts[0], int(parts[1])
            if frames < 1 or frames > 255:
                sys.exit(f"{path}:{lineno}: {frames} frames is out of range")
            out.append((name, frames))
    return out


def write_table(score, path, label):
    lines = [f"; Generated by tools/music_gen.py - do not edit.",
             f"; Source: {os.path.relpath(path)}", "", f"{label}:"]
    for name, frames in score:
        if name.upper() == "R":
            lines.append(f"\t\t.WORD\t1")          # a period nothing hears
            lines.append(f"\t\t.BYTE\t0, {frames}.")
        else:
            lines.append(f"\t\t.WORD\t{period(name)}.\t; {name}")
            lines.append(f"\t\t.BYTE\t{VOLUME}., {frames}.")
    lines.append("\t\t.WORD\t-1")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("score")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true",
                    help="accepted for symmetry with the other generators")
    ap.add_argument("--label", default="MUSIC_TITLE")
    args = ap.parse_args(argv)
    score = read_score(args.score)
    text = write_table(score, args.score, args.label)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"-> {args.out}: {len(score)} notes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
