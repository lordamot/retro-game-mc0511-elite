#!/usr/bin/env python3
"""font_gen.py - readable bitmap font -> MACRO-11 glyph data.

The resource is one block per character: a `char <octal code> <glyph>`
line, then rows of '#' and '.'. A `height N` line sets the row count
(eight by default). Codes run 040..137 octal, which
is ASCII punctuation and digits followed by Cyrillic in KOI-7 order -
the encoding the original's own text uses, so extracted strings need no
translation.

Emits FONT8, with **bit 0 as the leftmost pixel**, which is the order
the УКНЦ's planes want, plus FONT_FIRST/FONT_LAST/FONT_ROWS.

    python3 tools/font_gen.py src/res/font/uknc11.txt --out build/font8.mac
    python3 tools/font_gen.py bin/ukncbtl/uknc_rom.bin --uknc-rom --out tmp/uknc11.txt
"""

import argparse
import os
import sys
import hashlib
from pathlib import Path


def read_font(path):
    """Parse the resource.  A '#' only starts a comment OUTSIDE a glyph -
    inside one it is a lit pixel, and a row like '###.....' is data."""
    glyphs = {}
    code = None
    rows = []
    height = 8
    with open(path, encoding="utf-8") as fh:
        for lineno, raw in enumerate(fh, 1):
            s = raw.rstrip("\n").strip()
            if code is not None and len(rows) < height:
                if not s:
                    continue
                if len(s) != 8 or set(s) - set("#."):
                    raise SystemExit(f"{path}:{lineno}: bad glyph row {s!r}")
                rows.append(s)
                if len(rows) == height:
                    glyphs[code] = rows
                    code, rows = None, []
                continue
            if not s or s.startswith("#"):
                continue
            if s.startswith("height "):
                height = int(s.split()[1])
                if glyphs or not 1 <= height <= 32:
                    raise SystemExit(f"{path}:{lineno}: invalid font height")
            elif s.lower().startswith("char"):
                code = int(s.split()[1], 8)
                rows = []
            else:
                raise SystemExit(f"{path}:{lineno}: expected a 'char' line, "
                                 f"got {s!r}")
    if code is not None:
        raise SystemExit(f"{path}: glyph {code:03o} is short")
    return glyphs


def import_uknc_rom(source, out):
    """ROM's standard 8x11 bank at PPU 0120170, in KOI8 order.

    UKNCBTL qscreen.cpp's standard-font reader identifies this address;
    the startup PPU character-pointer table at 014142 agrees with it.
    Keep all eleven rows, including Cyrillic accents and descenders.
    """
    from elite_re import KOI7
    rom = Path(source).read_bytes()
    if not 16384 <= len(rom) <= 32768:
        raise SystemExit("error: expected a UKNC ROM between 16384 and 32768 bytes")
    base = 0o120170 - 0o100000
    lines = ["# Authentic UKNC ROM 8x11 font, remapped to the game's KOI-7.",
             "# Source: UKNCBTL uknc_rom.bin; PPU address 0120170.",
             f"# ROM SHA-256: {hashlib.sha256(rom).hexdigest()}",
             "# Reproduce with tools/font_gen.py ROM --uknc-rom --out FILE.",
             "# All eleven rows retained; bit 0 is the leftmost pixel.",
             "height 11", ""]
    for code in range(0o40, 0o140):
        ch = KOI7.get(chr(code), chr(code))
        index = ch.encode("koi8-r")[0]
        glyph = rom[base + (index - 32) * 11:base + (index - 31) * 11]
        lines.append(f"char {code:03o} {ch}")
        lines.extend("".join("#" if b & (1 << x) else "." for x in range(8))
                     for b in glyph)
        lines.append("")
    Path(out).write_text("\n".join(lines), encoding="utf-8")
    print(f"-> {out}: 64 authentic 8x11 glyphs")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("source")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--prefix", default="FONT",
                    help="assembly symbol prefix (default FONT)")
    ap.add_argument("--uknc-rom", action="store_true",
                    help="extract a readable 8x11 KOI-7 bank from the UKNC ROM")
    args = ap.parse_args(argv)
    if os.path.exists(args.out) and not args.force:
        sys.exit(f"error: {args.out} exists (use --force)")

    if args.uknc_rom:
        import_uknc_rom(args.source, args.out)
        return 0

    glyphs = read_font(args.source)
    if not glyphs:
        sys.exit(f"error: no glyphs in {args.source}")
    first, last = min(glyphs), max(glyphs)
    heights = {len(rows) for rows in glyphs.values()}
    if len(heights) != 1:
        sys.exit("error: inconsistent glyph heights")
    height = heights.pop()
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("; Generated by tools/font_gen.py - do not edit.\n")
        fh.write(f"; Source: {args.source}\n\n")
        prefix = args.prefix
        fh.write(f"{prefix}_FIRST = {first:o}\n")
        fh.write(f"{prefix}_LAST  = {last:o}\n\n")
        fh.write(f"{prefix}_ROWS = {height}.\n")
        fh.write(f"\t\t.IIF NE {prefix}_ROWS-FONT_H, .ERROR\n\n")
        fh.write(f"{prefix}8:\n")
        for code in range(first, last + 1):
            rows = glyphs.get(code, ["........"] * height)
            vals = []
            for r in rows:
                b = 0
                for x, ch in enumerate(r):
                    if ch == "#":
                        b |= 1 << x        # bit 0 = leftmost pixel
                vals.append(f"{b:o}")
            fh.write(f"\t\t.BYTE\t{', '.join(vals)}\t; {code:03o}\n")
    print(f"-> {args.out}: {len(glyphs)} glyphs, "
          f"{first:03o}..{last:03o}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
