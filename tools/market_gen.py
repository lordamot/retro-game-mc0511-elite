#!/usr/bin/env python3
"""market_gen.py - src/res/legend/market/goods.txt -> MACRO-11 data.

Elite Legend's 38 commodities (tools/legend_tables.py's extract of
TableBasePrice in Galaxy/GalaxyData.a80, with the Russian names), as
GOODS, one 6-byte record a good in Legend's order, which the market
(src/ovl_trade.mac) and the scoop (src/cargo.mac) walk:

    .BYTE price         the base price byte
    .BYTE grad          the gradient byte: bit 7 the sign, bits 4-0 the
                        amount, times the economy
    .BYTE quant         the base quantity
    .BYTE mask          what of the system's random byte joins in
    .BYTE unit, 0       0 tonnes, 1 kilogrammes, 2 grammes - Legend's
                        PrnNumProduct: gold and platinum by the
                        kilogramme, gem stones by the gramme, the rest
                        by the tonne

plus GOODNAMES, a word a good pointing at its name in KOI-7, and
NGOODS.

    python3 tools/market_gen.py src/res/legend/market/goods.txt --out build/market.mac
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from text_gen import to_koi7                     # noqa: E402

KG = (13, 14)           # gold, platinum
G = (15,)               # gem stones


def read_goods(path):
    rows = []
    with open(path, encoding="utf-8") as fh:
        for lineno, raw in enumerate(fh, 1):
            line = raw.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            head, _, name = line.partition("|")
            f = head.split()
            if len(f) != 6:
                sys.exit(f"{path}:{lineno}: expected 6 fields, got {len(f)}")
            n, key, price, grad, quant, mask = f
            rows.append((int(n), key, int(price), int(grad), int(quant),
                         int(mask), name.strip()))
    for i, r in enumerate(rows):
        if r[0] != i:
            sys.exit(f"{path}: row {i} is numbered {r[0]}")
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("source")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    if os.path.exists(args.out) and not args.force:
        sys.exit(f"error: {args.out} exists (use --force)")
    rows = read_goods(args.source)

    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("; Generated by tools/market_gen.py - do not edit.\n")
        fh.write(f"; Source: {args.source}\n\n")
        fh.write(f"NGOODS\t= {len(rows)}.\n")
        fh.write("G.PRICE\t= 0\nG.GRAD\t= 1\nG.QUANT\t= 2\n"
                 "G.MASK\t= 3\nG.UNIT\t= 4\nG.SIZE\t= 6\n\n")
        fh.write("GOODS:\n")
        for n, key, price, grad, quant, mask, name in rows:
            unit = 1 if n in KG else 2 if n in G else 0
            fh.write(f"\t\t.BYTE\t{price}., {grad}., {quant}., {mask}., "
                     f"{unit}., 0\t; {n} {key}\n")
        fh.write("\nGOODNAMES:\n")
        for n, *_ in rows:
            fh.write(f"\t\t.WORD\tGN_{n}\n")
        for n, key, price, grad, quant, mask, name in rows:
            body = ", ".join(f"{b}." for b in to_koi7(name, f"good {n}"))
            fh.write(f"GN_{n}:\t.BYTE\t{body}, 0\t; {name}\n")
        fh.write("\t\t.EVEN\n")
    print(f"-> {args.out}: {len(rows)} goods")


if __name__ == "__main__":
    main()
