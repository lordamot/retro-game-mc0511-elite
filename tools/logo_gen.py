#!/usr/bin/env python3
"""logo_gen.py - Elite Legend's title logo: extract it, and compile it.

The title screen shows the logo Legend opens on (GFX/logoscr_release.scr,
a ZX Spectrum screen that Legend keeps in RAM page 7 and shows at start):
the winged emblem in yellow under the words ELITE LEGEND.  It is kept in
the repository as TEXT, one character a pixel, so it can be edited like
every other resource here:

    .   black
    Y   yellow  - plane 2 on the УКНЦ (colour 4 in the view band)
    W   white   - plane 1 (colour 2); Legend draws its lettering cyan,
                  which the CPU cannot write (cyan needs plane 0)

Every 8x8 cell is one colour, as on the Spectrum; the compiler checks it.

    python3 tools/logo_gen.py --extract GFX.scr --out src/res/legend/logo.txt
    python3 tools/logo_gen.py src/res/legend/logo.txt --out build/logo.mac

The compiled form is for src/title.mac: LOGO_W bytes a row, LOGO_H rows,
the rows as one run-length stream (a control byte c: 0..127 is c+1
literal bytes following, 128..255 is c-127 empty bytes) of bytes in the
УКНЦ's order (bit 0 the leftmost pixel), and LOGO_CM, three bytes a row
of cells, bit i set where cell i is white.
"""

import argparse
import sys
from pathlib import Path

INK_YELLOW, INK_CYAN = 6, 5
COL0, NCOLS = 5, 22          # the byte columns the emblem and the words use


def extract(scr: Path) -> str:
    d = scr.read_bytes()
    if len(d) != 6912:
        sys.exit(f"error: {scr} is not a 6912-byte Spectrum screen")

    def byte(cx, y):
        return d[((y & 0xC0) << 5) | ((y & 7) << 8) | ((y & 0x38) << 2) | cx]

    def ink(cx, cy):
        return d[6144 + cy * 32 + cx] & 7

    lines = ["# Elite Legend's title logo, from GFX/logoscr_release.scr (byte",
             f"# columns {COL0}..{COL0 + NCOLS - 1} of the Spectrum screen, all 192 rows).",
             "# . black, Y yellow (plane 2), W white (plane 1, Legend's cyan);",
             "# one colour an 8x8 cell.  tools/logo_gen.py compiles it."]
    for y in range(192):
        row = []
        for cx in range(COL0, COL0 + NCOLS):
            k = ink(cx, y // 8)
            b = byte(cx, y)
            ch = "Y" if k == INK_YELLOW else ("W" if k == INK_CYAN else None)
            for bit in range(8):
                row.append(ch if ch and b & (0x80 >> bit) else ".")
        lines.append("".join(row))
    return "\n".join(lines) + "\n"


def compile_logo(txt: Path) -> str:
    rows = [ln.rstrip("\n") for ln in txt.read_text(encoding="utf-8").splitlines()
            if ln and not ln.startswith("#")]
    w = len(rows[0])
    if w % 8 or any(len(r) != w for r in rows) or len(rows) % 8:
        sys.exit("error: the logo must be a whole number of 8x8 cells, every row the same width")
    wb, h = w // 8, len(rows)
    bad = set("".join(rows)) - set(".YW")
    if bad:
        sys.exit(f"error: the logo has characters it cannot draw: {sorted(bad)}")
    cm = []
    for cy in range(h // 8):
        bits = 0
        for cx in range(wb):
            cell = {rows[cy * 8 + r][cx * 8 + k] for r in range(8) for k in range(8)} - {"."}
            if len(cell) > 1:
                sys.exit(f"error: cell {cx},{cy} is two colours")
            if cell == {"W"}:
                bits |= 1 << cx
        cm += [bits & 0xFF, (bits >> 8) & 0xFF, (bits >> 16) & 0xFF]
    flat = []
    for r in rows:
        for cx in range(wb):
            b = 0
            for k in range(8):                    # bit 0 is the leftmost pixel
                if r[cx * 8 + k] != ".":
                    b |= 1 << k
            flat.append(b)
    rle, i = [], 0
    while i < len(flat):
        j = i
        if flat[i] == 0:
            while j < len(flat) and flat[j] == 0 and j - i < 128:
                j += 1
            rle.append(127 + (j - i))
        else:
            while j < len(flat) and flat[j] != 0 and j - i < 128:
                j += 1
            rle.append(j - i - 1)
            rle += flat[i:j]
        i = j
    out = ["; Generated by tools/logo_gen.py - do not edit.",
           f"; Source: {txt.as_posix()} ({wb * 8}x{h}, {len(rle)} bytes run-length coded)",
           "",
           f"LOGO_W	= {wb}.",
           f"LOGO_H	= {h}.",
           "LOGO_CM:"]
    for k in range(0, len(cm), 12):
        out.append("\t\t.BYTE\t" + ", ".join(f"{v}." for v in cm[k:k + 12]))
    out.append("LOGO_RLE:")
    for k in range(0, len(rle), 16):
        out.append("\t\t.BYTE\t" + ", ".join(f"{v}." for v in rle[k:k + 16]))
    out.append("\t\t.EVEN")
    return "\n".join(out) + "\n", len(rle), wb, h


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("src", nargs="?", help="the logo as text, to compile")
    ap.add_argument("--extract", metavar="SCR", help="a Spectrum screen to extract the logo from")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true", help="accepted for the build; always writes")
    args = ap.parse_args(argv)
    if args.extract:
        Path(args.out).write_text(extract(Path(args.extract)), encoding="utf-8")
        print(f"-> {args.out}: extracted")
        return
    if not args.src:
        sys.exit("error: give the logo's text file, or --extract")
    text, n, wb, h = compile_logo(Path(args.src))
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"-> {args.out}: {wb * 8}x{h}, {n} bytes")


if __name__ == "__main__":
    main()
