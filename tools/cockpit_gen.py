#!/usr/bin/env python3
"""cockpit_gen.py - Legend's cockpit blocks -> a MACRO-11 table for the resident.

    python3 tools/cockpit_gen.py src/res/legend/cockpits.txt src/res/legend/catalog.txt --out build/legend_cockpit.mac

The twenty blocks' rule fields, a table a column, indexed by cockpit
number; and from the catalogue, which cockpit and which hull each of
the twenty ships has, indexed by P_SHIP - 1, so that the resident can
set the ship's limits without loading the outfitter's copy of the
catalogue (COCKPIT_SET in src/cockpit.mac):

    NCOCKPITS       20
    CK_MAXMISS      .BYTE a cockpit: missiles the rack holds
    CK_ENUNITS      .BYTE a cockpit: energy banks
    CK_MAXFUEL      .BYTE a cockpit: tenths of a light year in the tank
    CK_TURRETS      .BYTE a cockpit: 0 none, 1 front, 2 front/rear, 4 all
    CK_SCANNER      .BYTE a cockpit: the scanner variant
    CK_TONS         .WORD a cockpit: the hold, without the larger bay
    SHIP_CKPT       .BYTE a ship: its cockpit
    SHIP_HULLNO     .BYTE a ship: its hull, AdrDataShips number (the
                    port's type less one)
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from catalog_gen import read_catalog   # noqa: E402

FIELDS = ["maxmiss", "enunits", "maxfuel", "tonnage", "turrets", "scanner"]


def read_cockpits(path):
    rows = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            n, _, vals = line.partition("|")
            v = vals.split()
            if len(v) != len(FIELDS):
                sys.exit(f"{path}: cannot read: {line!r}")
            r = dict(zip(FIELDS, (int(x) for x in v)))
            if int(n) != len(rows):
                sys.exit(f"{path}: cockpit {len(rows)} is numbered {n}")
            rows.append(r)
    return rows


def emit(cockpits, ships, sources):
    out = ["; Generated by tools/cockpit_gen.py - do not edit.",
           f"; Sources: {', '.join(sources)}", "",
           f"NCOCKPITS\t= {len(cockpits)}.", ""]
    for label, field in (("CK_MAXMISS", "maxmiss"), ("CK_ENUNITS", "enunits"),
                         ("CK_MAXFUEL", "maxfuel"), ("CK_TURRETS", "turrets"),
                         ("CK_SCANNER", "scanner")):
        out.append(f"{label}:\t.BYTE\t" + ", ".join(f"{r[field]}." for r in cockpits))
    out.append("\t\t.EVEN")
    out.append("CK_TONS:\t.WORD\t" + ", ".join(f"{r['tonnage']}." for r in cockpits))
    for s in ships:
        if not 0 <= s["cockpit"] < len(cockpits):
            sys.exit(f"ship {s['n']} has cockpit {s['cockpit']}")
    out.append("SHIP_CKPT:\t.BYTE\t" + ", ".join(f"{s['cockpit']}." for s in ships))
    out.append("SHIP_HULLNO:\t.BYTE\t" + ", ".join(f"{s['obj']}." for s in ships))
    out.append("\t\t.EVEN")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("cockpits", help="src/res/legend/cockpits.txt")
    ap.add_argument("catalog", help="src/res/legend/catalog.txt")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args(argv)
    if os.path.exists(args.out) and not args.force:
        sys.exit(f"error: {args.out} exists (use --force)")
    cockpits = read_cockpits(args.cockpits)
    ships = read_catalog(args.catalog)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(emit(cockpits, ships, [args.cockpits, args.catalog]))
    print(f"-> {args.out}: {len(cockpits)} cockpits, {len(ships)} ships")
    return 0


if __name__ == "__main__":
    sys.exit(main())
