#!/usr/bin/env python3
"""Elite Legend's equipment table as a MACRO-11 module.

Reads src/res/legend/equip.txt (tools/legend_tables.py's extract of
INCLUDE/Menu/priceEquip.a80, DevicesRus.a80 and AdrTablEquip) and
writes build/legend_equip.mac: the 49 Russian names as KOI-7 strings
with a word table over them, the tech level and mission gate a byte
each, the two prices 32-bit, and the device map for rows 14 on - which
byte of the record's P_DEVICES a row is and which type in its low bits.

    NEQL            rows
    EQL_NAMES       .WORD, a string address a row
    EQL_TECH        .BYTE a row: minimum tech level, 255 = Raxxla only
    EQL_MISSION     .BYTE a row: the PilotMissionComplete gate
    EQL_PRICE       .WORD low, high a row: tenths, at a station
    EQL_MILPRICE    the same at a military station, 0 = not sold there
    EQL_DEV0        the first device row (14)
    EQL_DEV         .BYTE from that row: type * 64 + device index

The pilot page (src/ovl_pilot.mac) reads the names and the device map;
the outfitter will read the rest when it becomes Legend's.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from text_gen import to_koi7                     # noqa: E402


def read_equip(path):
    rows = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            head, _, name = line.partition("|")
            f = head.split()
            if len(f) != 7:
                sys.exit(f"{path}: cannot read: {line!r}")
            n, label, tech, mission, ps, pm, dev = f
            rows.append({"n": int(n), "label": label, "tech": int(tech),
                         "mission": int(mission), "price": int(ps),
                         "milprice": int(pm),
                         "dev": None if dev == "-" else int(dev),
                         "name": name.strip()})
    for i, r in enumerate(rows):
        if r["n"] != i:
            sys.exit(f"{path}: row {i} is numbered {r['n']}")
    return rows


def emit(rows, source, part="all"):
    """PART is what the overlay assembling it reads: "all" for the
    outfitter, "names" (the names and the device map) for the pilot
    page, "price" (the prices alone) for the yard - an overlay carries
    only the columns it uses, and the window is sized by the largest."""
    out = ["; Generated by tools/legend_gen.py - do not edit.",
           f"; Source: {source} (part: {part})", "",
           f"NEQL\t= {len(rows)}.", ""]
    if part in ("all", "names"):
        out.append("EQL_NAMES:")
        for r in rows:
            out.append(f"\t\t.WORD\tEQL_N{r['n']}")
    if part == "all":
        out.append("EQL_TECH:\t.BYTE\t" + ", ".join(f"{r['tech']}." for r in rows))
        out.append("EQL_MISSION:\t.BYTE\t" + ", ".join(f"{r['mission']}." for r in rows))
        out.append("\t\t.EVEN")
    if part in ("all", "price"):
        out.append("EQL_PRICE:")
        for r in rows:
            out.append(f"\t\t.WORD\t{r['price'] & 0xFFFF}., {r['price'] >> 16}.\t; {r['n']}")
    if part == "all":
        out.append("EQL_MILPRICE:")
        for r in rows:
            out.append(f"\t\t.WORD\t{r['milprice'] & 0xFFFF}., {r['milprice'] >> 16}.")
    devs = [r for r in rows if r["dev"] is not None]
    first = devs[0]["n"]
    if [r["n"] for r in devs] != list(range(first, first + len(devs))):
        sys.exit("the device rows are not one run")
    if part in ("all", "names"):
        out.append(f"EQL_DEV0\t= {first}.")
        out.append("EQL_DEV:\t.BYTE\t" + ", ".join(f"{r['dev']}." for r in devs))
        out.append("\t\t.EVEN")
        for r in rows:
            data = to_koi7(r["name"], f"equipment {r['n']}")
            body = ", ".join(f"{b}." for b in data) or "0"
            out.append(f"EQL_N{r['n']}:\t.BYTE\t{body}, 0\t; {r['name']}")
    out.append("\t\t.EVEN")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("source", help="src/res/legend/equip.txt")
    ap.add_argument("--out", required=True)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--part", choices=["all", "names", "price"], default="all",
                    help="which columns: all (the outfitter), names (the pilot page), price (the yard)")
    args = ap.parse_args(argv)
    if os.path.exists(args.out) and not args.force:
        sys.exit(f"error: {args.out} exists (use --force)")
    rows = read_equip(args.source)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(emit(rows, args.source, args.part))
    print(f"-> {args.out}: {len(rows)} equipment rows ({args.part})")


if __name__ == "__main__":
    main()
